"""Golden parity: the engine reproduces every cached Calculations / Print Report
value of the workbook's Excelcior Shipping example (fixtures/golden_excelcior.json,
generated by scripts/export_golden.py from the workbook)."""
from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path

import pytest

from app.domain.engine import run_engine
from app.domain.models import EngineInputs

FIXTURE = json.loads(
    (Path(__file__).resolve().parents[1] / "fixtures" / "golden_excelcior.json").read_text(encoding="utf-8")
)
CALC = FIXTURE["calculations"]
REL, ABS = 1e-9, 1e-12


def excelcior_inputs() -> EngineInputs:
    return EngineInputs(
        years_total=10.0,
        amortised_amount=0.0,
        bullet_amount=75_000_000.0,
        bullet_rate=0.078,
        share_value=FIXTURE["input_derived"]["share_value"],
        dividend_yield=0.0561,
        dividends_repaid=1.0,
        volatility=0.25,
        equity_volatility=0.25,
        structure="Bullet Payment",
        risk_free_rate=0.06,
        dcr_schedule=[(0.0, 1.75)],
        rate_schedule=[(0.0, 0.078)],
        reference_grade="SB11",
        approach=1,
        listing="Listed",
        unwind_years=FIXTURE["input_derived"]["unwind_years"],
    )


@pytest.fixture(scope="module")
def result():
    return run_engine(excelcior_inputs())


SERIES = (
    "years", "dt", "dcr", "avg_loan", "avg_share_value", "spv_pd_covenant", "spv_pd",
    "spv_pd_no_covenant", "issuer_default_rate", "issuer_lgd", "spv_lgd",
    "covenant_effectiveness", "combined_pd", "combined_lgd",
)


@pytest.mark.parametrize("name", SERIES)
def test_year_series_match_workbook(result, name):
    key = "year" if name == "years" else name
    got = [getattr(r, key) for r in result.years]
    assert got == pytest.approx(CALC[name], rel=REL, abs=ABS), name


def test_results_block_matches_workbook(result):
    exp = CALC["results"]
    got = asdict(result.results)
    for key, value in exp.items():
        if isinstance(value, str):
            assert got[key] == value, key
        else:
            assert got[key] == pytest.approx(value, rel=REL, abs=ABS), key


@pytest.mark.parametrize("column", ("reference", "client", "combined"))
def test_print_report_matches_workbook(result, column):
    exp = FIXTURE["report"][column]
    got = asdict(result.report[column])
    for key, value in exp.items():
        if isinstance(value, str):
            assert got[key] == value, key
        else:
            assert got[key] == pytest.approx(value, rel=REL, abs=ABS), key
    if column == "reference":
        assert got["rwa_pct"] == 2.0


def test_derived_values(result):
    assert result.derived["discount_factor"] == pytest.approx(CALC["e49_discount_factor"], rel=REL)
    assert result.derived["fsh"] == CALC["fsh"]
    assert result.derived["reference_pd"] == 0.0032
    assert result.warnings == []


def test_path_samples(result):
    paths = result.derived["path_samples"]
    for row, cols in CALC["path_samples"].items():
        p = int(row) - 7
        got = paths[p]
        assert got["stock_y1"] == pytest.approx(cols["AE"], rel=REL)
        assert got["cover_y1"] == pytest.approx(cols["AF"], rel=REL)
        assert got["survival_covenant_y1"] == cols["AG"]
        assert got["lgd_y1"] == pytest.approx(cols["AL"], rel=REL, abs=ABS)
        assert got["stock_y2"] == pytest.approx(cols["AN"], rel=REL)
        assert got["lgd_y2"] == pytest.approx(cols["BA"], rel=1e-6, abs=ABS)
