"""Cached loaders for the reference data exported from the workbook
(backend/app/data/reference/*.json, generated by scripts/export_reference.py)."""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

DATA = Path(__file__).resolve().parents[1] / "data" / "reference"


def _load(name: str):
    return json.loads((DATA / f"{name}.json").read_text(encoding="utf-8"))


@lru_cache
def pd_masterscale() -> list[dict]:
    return _load("pd_masterscale")


@lru_cache
def issuer_default_rates() -> dict[str, list[float]]:
    return _load("issuer_default_rates")


@lru_cache
def countries() -> list[dict]:
    return _load("countries")


@lru_cache
def _country_index() -> dict[str, dict]:
    return {c["name"]: c for c in countries()}


def country(name: str) -> dict | None:
    return _country_index().get(name)


@lru_cache
def sectors() -> list[str]:
    return _load("sectors")


def revenue_sizes() -> list[str]:
    return list(capture_lists()["revenue_sizes"])


@lru_cache
def volatilities_multiples() -> dict[str, dict]:
    return _load("volatilities_multiples")


@lru_cache
def sector_correlations() -> dict:
    return _load("sector_correlations")


@lru_cache
def lgd_buckets() -> list[dict]:
    return _load("lgd_buckets")


@lru_cache
def random_numbers() -> list[list[float]]:
    return _load("random_numbers")


@lru_cache
def simulation() -> dict:
    return _load("simulation")


@lru_cache
def capture_lists() -> dict:
    return _load("capture_lists")
